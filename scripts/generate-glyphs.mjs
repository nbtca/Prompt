/* global document */
// Measures how much ink each printable ASCII character puts in a 4 x 8 grid of its cell, and writes
// src/art/glyphs.ts. Needs Playwright with a Chromium, which is not a dependency of this package:
//   PLAYWRIGHT=/path/to/playwright/index.mjs node scripts/generate-glyphs.mjs
import { writeFileSync } from 'node:fs';

const { chromium } = await import(process.env.PLAYWRIGHT ?? 'playwright');
const COLS = 4;
const ROWS = 8;
const browser = await chromium.launch();
const page = await browser.newPage();
const table = await page.evaluate(
  async ({ cols, rows }) => {
    await document.fonts.load('200px "JetBrainsMono NFM"');
    const cellWidth = 120;
    const cellHeight = 264;
    const baseline = 204;
    const canvas = document.createElement('canvas');
    canvas.width = cellWidth;
    canvas.height = cellHeight;
    const context = canvas.getContext('2d', { willReadFrequently: true });
    const out = [];
    for (let code = 0x20; code < 0x7f; code++) {
      context.clearRect(0, 0, cellWidth, cellHeight);
      context.fillStyle = '#000';
      context.font = '200px "JetBrainsMono NFM"';
      context.textBaseline = 'alphabetic';
      context.fillText(String.fromCharCode(code), 0, baseline);
      const data = context.getImageData(0, 0, cellWidth, cellHeight).data;
      const cover = [];
      for (let row = 0; row < rows; row++) {
        for (let col = 0; col < cols; col++) {
          let sum = 0;
          const w = cellWidth / cols;
          const h = cellHeight / rows;
          for (let y = Math.floor(row * h); y < Math.floor((row + 1) * h); y++) {
            for (let x = Math.floor(col * w); x < Math.floor((col + 1) * w); x++)
              sum += data[(y * cellWidth + x) * 4 + 3] ?? 0;
          }
          cover.push(Math.round(sum / (w * h)));
        }
      }
      out.push(cover.map((value) => value.toString(16).padStart(2, '0')).join(''));
    }
    return out;
  },
  { cols: COLS, rows: ROWS },
);
await browser.close();
const body = table.map((hex) => `  '${hex}',`).join('\n');
writeFileSync(
  'src/art/glyphs.ts',
  `// Generated by scripts/generate-glyphs.mjs from JetBrains Mono; edit the script, not this file.\n// One entry per printable ASCII character from space to ~: ink coverage 00 to ff for a 4 x 8 grid, row by row.\nexport const GLYPH_COLS = ${COLS};\nexport const GLYPH_ROWS = ${ROWS};\nexport const GLYPHS: readonly string[] = [\n${body}\n];\n`,
);
console.log(`${table.length} glyphs`);
